#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

nix build .#docsOptionsJSON -o result-options

# ndg (github:feel-co/ndg) has no "emit a single markdown file" mode: its
# subcommands are `html` (renders a full multi-page site: index.html,
# search.html, assets/), `man`, and `pdf`. `html` is the only one that
# accepts our plain options.json via --module-options, so we render into a
# throwaway directory and lift just the per-option content fragment out of
# the generated options.html (a clean `<div class="options-container">`
# block with each option's type/default/description as plain HTML) — the
# rest of the scaffolded site (index/search/assets) is discarded since
# Docusaurus already provides that site chrome itself.
workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

nix run github:feel-co/ndg -- html \
  --module-options result-options/share/doc/nixos/options.json \
  --output-dir "$workdir" \
  --title "Declared Options" \
  --options-filter-prefix flake

{
  echo '---'
  echo 'title: Options'
  echo 'sidebar_position: 1'
  echo '---'
  echo
  echo '<!-- AUTO-GENERATED by ./scripts/gen-options.sh — do not edit by hand -->'
  echo
  sed -n '/<div class="options-container">/,/<div class="footnotes-container">/p' "$workdir/options.html" \
    | sed '$d' \
    | sed -e 's#<html><head></head><body>##g' -e 's#</body></html>##g' \
    | sed -E 's#(<div class="option-description">)(<p>)#\1\n\2#g'
} > website/docs/reference/options.md

rm -f result-options
