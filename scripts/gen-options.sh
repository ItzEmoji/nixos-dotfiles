#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

nix build .#docsOptionsJSON -o result-options

# ndg is run via the flake.lock-pinned `ndg` input (exposed as `packages.ndg`
# in modules/packages/docs-options.nix), not `nix run github:feel-co/ndg`,
# so this always executes the exact revision recorded in flake.lock rather
# than floating to whatever's latest on GitHub on each run.
#
# ndg has no "emit a single markdown file" mode: its subcommands are `html`
# (renders a full multi-page site: index.html, search.html, assets/), `man`,
# and `pdf`. `html` is the only one that accepts our plain options.json via
# --module-options, so we render into a throwaway directory and lift just
# the per-option content fragment out of the generated options.html (a
# clean `<div class="options-container">` block with each option's
# type/default/description as plain HTML) — the rest of the scaffolded site
# (index/search/assets) is discarded since Docusaurus already provides that
# site chrome itself.
workdir="$(mktemp -d)"
trap 'rm -rf "$workdir" result-options' EXIT

nix run .#ndg -- html \
  --module-options result-options/share/doc/nixos/options.json \
  --output-dir "$workdir" \
  --title "Declared Options" \
  --options-filter-prefix flake

# Guard against ndg changing its options.html template out from under us.
# GNU sed's `-n '/start/,/end/p'` range address fails *silently* (exit 0) if
# either marker is missing: a missing start marker prints nothing at all,
# and a missing end marker runs clean through to end-of-file — dumping the
# rest of options.html (closing tags, <script> assets, scaffolding) into
# options.md. Both would otherwise surface only later as a confusing MDX
# build error, not a clear message from this script. So check for both
# markers directly in ndg's raw output before trusting the sed extraction.
if ! grep -q '<div class="options-container">' "$workdir/options.html"; then
  echo "gen-options.sh: ndg's options.html has no <div class=\"options-container\"> — its template may have changed." >&2
  echo "Inspect $workdir/options.html and update the sed extraction in this script accordingly." >&2
  exit 1
fi
if ! grep -q '<div class="footnotes-container">' "$workdir/options.html"; then
  echo "gen-options.sh: ndg's options.html has no <div class=\"footnotes-container\"> — its template may have changed." >&2
  echo "Inspect $workdir/options.html and update the sed extraction in this script accordingly." >&2
  exit 1
fi

extracted="$workdir/options-fragment.html"
sed -n '/<div class="options-container">/,/<div class="footnotes-container">/p' "$workdir/options.html" \
  | sed '$d' \
  | sed -e 's#<html><head></head><body>##g' -e 's#</body></html>##g' \
        -e 's#<span class="copy-link"[^>]*></span>##g' -e 's#<span class="copy-feedback">[^<]*</span>##g' \
  | sed -E 's#(<div class="option-description">)(<p>)#\1\n\2#g' \
  > "$extracted"

# Belt-and-braces: even with both markers present, make sure the extraction
# actually produced real option content (e.g. in case the options filter
# matched zero options), rather than writing an empty/near-empty doc page.
if [ ! -s "$extracted" ] || ! grep -q 'class="option-name"' "$extracted"; then
  echo "gen-options.sh: extraction produced no option content." >&2
  echo "Inspect $workdir/options.html and update the sed extraction in this script accordingly." >&2
  exit 1
fi

{
  echo '---'
  echo 'title: Options'
  echo 'sidebar_position: 1'
  echo '---'
  echo
  echo '<!-- AUTO-GENERATED by ./scripts/gen-options.sh — do not edit by hand -->'
  echo
  cat "$extracted"
} > website/docs/reference/options.md
