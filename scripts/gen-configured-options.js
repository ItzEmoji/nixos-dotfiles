#!/usr/bin/env bun
'use strict';

const fs = require('fs');
const path = require('path');
const { findModuleAssignments, extractConfigRows } = require('./lib/nix-config-parser');

const REPO_ROOT = path.resolve(__dirname, '..');
const ROOTS = [
  'modules/nixosModules',
  'modules/homeManagerModules',
  'modules/wrappers',
  'modules/packages',
];

const CATEGORY_ORDER = ['NixOS System', 'NixOS Desktop', 'Home Manager', 'Wrappers & Packages'];

function walkNixFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkNixFiles(full));
    } else if (entry.isFile() && entry.name.endsWith('.nix')) {
      results.push(full);
    }
  }
  return results;
}

function categorize(relPath) {
  if (relPath.startsWith('modules/nixosModules/gui/') || relPath.startsWith('modules/nixosModules/videoDrivers/')) {
    return 'NixOS Desktop';
  }
  if (relPath.startsWith('modules/nixosModules/')) return 'NixOS System';
  if (relPath.startsWith('modules/homeManagerModules/')) return 'Home Manager';
  if (relPath.startsWith('modules/wrappers/') || relPath.startsWith('modules/packages/')) {
    return 'Wrappers & Packages';
  }
  return 'Other';
}

function moduleLabel(registry, name) {
  return `${registry}.${name}`;
}

function escapeTableCell(text) {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function main() {
  const byCategory = new Map(CATEGORY_ORDER.map((c) => [c, []]));

  for (const root of ROOTS) {
    const rootPath = path.join(REPO_ROOT, root);
    if (!fs.existsSync(rootPath)) continue;
    for (const file of walkNixFiles(rootPath)) {
      const relPath = path.relative(REPO_ROOT, file);
      const category = categorize(relPath);
      if (category === 'Other') continue;
      const source = fs.readFileSync(file, 'utf8');
      for (const { registry, name, bodyText } of findModuleAssignments(source)) {
        for (const row of extractConfigRows(bodyText, { maxDepth: 4 })) {
          byCategory.get(category).push({
            path: row.path,
            value: row.value,
            module: moduleLabel(registry, name),
          });
        }
      }
    }
  }

  const lines = [];
  lines.push('---');
  lines.push('title: Configured Options');
  lines.push('sidebar_position: 2');
  lines.push('---');
  lines.push('');
  lines.push('<!-- AUTO-GENERATED by `bun run scripts/gen-configured-options.js` — do not edit by hand -->');
  lines.push('');
  lines.push('# Configured Options');
  lines.push('');
  lines.push(
    "Every concrete option value this repo's modules actually set, extracted " +
    "directly from source (no Nix evaluation). This is a different question " +
    "from [Options](./options) (the ndg-generated page, which only documents " +
    "formally declared `mkOption`s — of which this repo has exactly one): " +
    "this page shows every upstream NixOS/home-manager option this repo " +
    "assigns a value to, however it does it. Regenerate with " +
    "`bun run scripts/gen-configured-options.js`."
  );
  lines.push('');

  let total = 0;
  for (const category of CATEGORY_ORDER) {
    const rows = byCategory.get(category);
    if (rows.length === 0) continue;
    rows.sort((a, b) => a.path.localeCompare(b.path));
    total += rows.length;
    lines.push(`## ${category}`);
    lines.push('');
    lines.push('| Option path | Value | Set in |');
    lines.push('|---|---|---|');
    for (const row of rows) {
      lines.push(
        `| \`${escapeTableCell(row.path)}\` | \`${escapeTableCell(row.value)}\` | \`${escapeTableCell(row.module)}\` |`
      );
    }
    lines.push('');
  }

  const outPath = path.join(REPO_ROOT, 'website/docs/reference/configured-options.md');
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log(`Wrote ${outPath} (${total} rows)`);
}

main();
